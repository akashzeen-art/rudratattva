export function getAllSubcategoryRoutes() {
  const out = []
  const addLink = (item, parent) => {
    if (!item?.to) return
    out.push({ path: item.to, title: item.label || item.title, img: item.img, parent })
  }
  const walkCol = (col, root) => {
    if (col.title && col.to) addLink({ label: col.title, to: col.to, img: col.img }, root)
    ;(col.links || []).forEach(l => addLink(l, root))
    ;(col.sections || []).forEach(sec => {
      if (sec.title && sec.to) addLink({ label: sec.title, to: sec.to }, root)
      ;(sec.links || []).forEach(l => addLink(l, root))
    })
  }
  navLinks.forEach(nav => {
    ;(nav.dropdown?.columns || []).forEach(col => walkCol(col, { title: nav.label, to: nav.to }))
    if (nav.dropdown?.footerLink) addLink(nav.dropdown.footerLink, { title: nav.label, to: nav.to })
  })
  return out
}

/** L2 cards for main category pages */
export function getMainCategoryCards(key) {
  const map = { rudraksha: rudrakshaDropdown, gemstones: gemstonesDropdown, yantra: yantraDropdown, idols: idolsDropdown, pujas: pujasDropdown }
  const dd = map[key]
  if (!dd) return []
  const cards = []
  dd.columns.forEach(col => {
    if (col.title && col.to) cards.push({ label: col.title, to: col.to, img: col.img })
    else if (col.headerOnly) (col.links || []).forEach(l => cards.push(l))
    ;(col.sections || []).forEach(sec => { if (sec.title && sec.to) cards.push({ label: sec.title, to: sec.to, img: sec.img }) })
  })
  if (dd.footerLink) cards.push(dd.footerLink)
  return cards
}
